#!/usr/bin/env node
// Knowledge base tooling. No dependencies. Conventions: docs/README.md.
//
//   node scripts/wiki.mjs            write docs/index/ from the pages' `covers`
//   node scripts/wiki.mjs check      fail if the index is stale or the wiki breaks a convention
//   node scripts/wiki.mjs affected [files...]
//                                    list pages whose `covers` match the files
//                                    (default: uncommitted changes; `-` reads stdin)

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = process.env.WIKI_ROOT ?? path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const WIKI = "docs/wiki";
const INDEX = "docs/index";
const MAX_GLOSSARY_LINE = 160;
const INDEX_HEADER =
  "<!-- Generated by `node scripts/wiki.mjs` from the wiki pages' `covers`. Do not edit. -->";

export function readWikiConfig(root) {
  const file = path.join(root, "harness.json");
  if (!fs.existsSync(file)) return undefined;
  let harness;
  try {
    harness = JSON.parse(fs.readFileSync(file, "utf8"));
  } catch (error) {
    throw new Error(`${file}: ${error.message}`);
  }
  return harness.wiki;
}

let sourceDirsCache;
function sourceDirs() {
  sourceDirsCache ??= readWikiConfig(ROOT)?.sourceDirs ?? [];
  return sourceDirsCache;
}

// ---------- files ----------

const posix = (p) => p.split(path.sep).join("/");
const read = (rel) => fs.readFileSync(path.join(ROOT, rel), "utf8");
const exists = (rel) => fs.existsSync(path.join(ROOT, rel));

function walk(dir, skip = new Set(["node_modules", ".git", "dist", ".wrangler"])) {
  const out = [];
  const abs = path.join(ROOT, dir);
  if (!fs.existsSync(abs)) return out;
  for (const entry of fs.readdirSync(abs, { withFileTypes: true })) {
    if (skip.has(entry.name)) continue;
    const rel = dir ? `${dir}/${entry.name}` : entry.name;
    if (entry.isDirectory()) out.push(...walk(rel, skip));
    else if (entry.isFile()) out.push(rel);
  }
  return out;
}

function git(...args) {
  return execFileSync("git", args, { cwd: ROOT, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] });
}

// Tracked and untracked-but-not-ignored files; a plain walk where git is missing.
function repoFiles() {
  try {
    // A file in a merge conflict is listed once per stage, hence the Set.
    const listed = git("ls-files", "--cached", "--others", "--exclude-standard", "-z").split("\0");
    return [...new Set(listed)].filter((f) => f && exists(f)).sort();
  } catch {
    return walk("").sort();
  }
}

// ---------- globs ----------

function globToRegExp(glob) {
  let re = "";
  for (let i = 0; i < glob.length; i++) {
    const c = glob[i];
    if (c === "*" && glob[i + 1] === "*") {
      if (glob[i + 2] === "/") {
        re += "(?:.*/)?";
        i += 2;
      } else {
        re += ".*";
        i += 1;
      }
    } else if (c === "*") re += "[^/]*";
    else if (c === "?") re += "[^/]";
    else re += c.replace(/[.+^${}()|[\]\\]/g, "\\$&");
  }
  return new RegExp(`^${re}$`);
}

// ---------- markdown ----------

function frontmatter(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---\n/);
  if (!m) return { covers: null, body: text, bodyStart: 0 };
  const covers = [];
  let inCovers = false;
  for (const line of m[1].split("\n")) {
    if (/^covers:\s*$/.test(line)) inCovers = true;
    else if (inCovers && /^\s+-\s+/.test(line)) covers.push(line.replace(/^\s+-\s+/, "").replace(/^["']|["']$/g, "").trim());
    else if (/^\S/.test(line)) inCovers = false;
  }
  return { covers, body: text.slice(m[0].length), bodyStart: m[0].split("\n").length - 1 };
}

// Lines outside fenced code blocks, with inline code removed.
function proseLines(text) {
  const out = [];
  let fence = false;
  text.split("\n").forEach((line, i) => {
    if (/^\s*(```|~~~)/.test(line)) {
      fence = !fence;
      return;
    }
    if (!fence) out.push({ n: i + 1, raw: line, text: line.replace(/`[^`]*`/g, "``") });
  });
  return out;
}

// GitHub's heading anchors.
function slug(heading) {
  return heading
    .trim()
    .toLowerCase()
    .replace(/<[^>]+>/g, "")
    .replace(/[^\p{L}\p{N}\s_-]/gu, "")
    .replace(/\s/g, "-");
}

function headings(text) {
  const out = [];
  const seen = new Map();
  for (const { n, raw } of proseLines(text)) {
    const m = raw.match(/^(#{1,6})\s+(.*?)\s*#*\s*$/);
    if (!m) continue;
    const base = slug(m[2]);
    const count = seen.get(base) ?? 0;
    seen.set(base, count + 1);
    out.push({ n, level: m[1].length, title: m[2], anchor: count ? `${base}-${count}` : base });
  }
  return out;
}

function links(text) {
  const out = [];
  for (const { n, text: line } of proseLines(text)) {
    for (const m of line.matchAll(/\]\(([^)\s]+)(?:\s+"[^"]*")?\)/g)) out.push({ n, target: m[1] });
  }
  return out;
}

// ---------- model ----------

function loadWiki() {
  const files = repoFiles();
  const mdFiles = files.filter((f) => f.startsWith(`${WIKI}/`) && f.endsWith(".md"));
  const pages = [];
  const glossaries = [];
  for (const file of mdFiles) {
    const text = read(file);
    const rel = file.slice(WIKI.length + 1);
    const topic = rel.includes("/") ? rel.split("/")[0] : null;
    if (path.posix.basename(file) === "glossary.md") {
      glossaries.push({ file, topic, text, terms: parseGlossary(file, text) });
      continue;
    }
    const { covers } = frontmatter(text);
    const h1 = headings(text).find((h) => h.level === 1);
    pages.push({ file, topic, text, covers: covers ?? [], hasFrontmatter: covers !== null, title: h1?.title ?? rel });
  }
  for (const page of pages) {
    page.matchers = page.covers.map((glob) => ({ glob, re: globToRegExp(glob) }));
    page.files = files.filter((f) => page.matchers.some((m) => m.re.test(f)));
  }
  return { files, pages, glossaries };
}

function parseGlossary(file, text) {
  const terms = [];
  for (const { n, raw } of proseLines(text)) {
    const m = raw.match(/^- \*\*(.+?)\*\*/);
    if (!m) continue;
    const targets = [...raw.matchAll(/\]\(([^)\s]+)\)/g)].map((l) => resolveLink(file, l[1]));
    terms.push({ n, line: raw, name: m[1], targets });
  }
  return terms;
}

function resolveLink(from, target) {
  const [p, anchor = null] = target.split("#");
  const file = p ? path.posix.normalize(path.posix.join(path.posix.dirname(from), decodeURI(p))) : from;
  return { file, anchor };
}

const relLink = (from, to) => path.posix.relative(path.posix.dirname(from), to);

// ---------- index ----------

function sourceFiles(files) {
  return files.filter((f) => sourceDirs().some((d) => f.startsWith(`${d}/`)));
}

function buildIndex(wiki) {
  const byDir = new Map();
  for (const f of sourceFiles(wiki.files)) {
    const dir = path.posix.dirname(f);
    if (!byDir.has(dir)) byDir.set(dir, []);
    byDir.get(dir).push(f);
  }
  const allTerms = wiki.glossaries.flatMap((g) => g.terms.map((t) => ({ ...t, glossary: g })));
  const out = new Map();
  for (const [dir, files] of [...byDir].sort(([a], [b]) => a.localeCompare(b))) {
    const target = `${INDEX}/${dir}.md`;
    const pagesFor = (f) => wiki.pages.filter((p) => p.files.includes(f));
    const pages = wiki.pages
      .map((p) => ({ p, count: files.filter((f) => p.files.includes(f)).length }))
      .filter((x) => x.count)
      .sort((a, b) => b.count - a.count || a.p.file.localeCompare(b.p.file))
      .map((x) => x.p);
    const pageFiles = new Set(pages.map((p) => p.file));
    const terms = allTerms.filter((t) => t.targets.some((l) => pageFiles.has(l.file)));

    const lines = [`# ${dir}`, "", INDEX_HEADER, "", "## Read", ""];
    if (pages.length) for (const p of pages) lines.push(`- [${p.title}](${relLink(target, p.file)})`);
    else lines.push("No page covers this directory.");
    lines.push("", "## Terms", "");
    if (terms.length) {
      for (const t of terms) {
        lines.push(t.line.replace(/\]\(([^)\s]+)\)/g, (_, l) => {
          const { file, anchor } = resolveLink(t.glossary.file, l);
          return `](${relLink(target, file)}${anchor ? `#${anchor}` : ""})`;
        }));
      }
    } else lines.push("No terms.");
    lines.push("", "## Files", "");
    for (const f of files) {
      const ps = pagesFor(f);
      const name = path.posix.basename(f);
      lines.push(`- \`${name}\` — ${ps.length ? ps.map((p) => `[${p.title}](${relLink(target, p.file)})`).join(", ") : "not covered"}`);
    }
    out.set(target, `${lines.join("\n")}\n`);
  }
  return out;
}

function currentIndexFiles() {
  return walk(INDEX).filter((f) => f.endsWith(".md") && f !== `${INDEX}/README.md`);
}

function writeIndex() {
  const wiki = loadWiki();
  const index = buildIndex(wiki);
  let changed = 0;
  for (const stale of currentIndexFiles()) {
    if (!index.has(stale)) {
      fs.rmSync(path.join(ROOT, stale));
      changed++;
      console.log(`removed ${stale}`);
    }
  }
  for (const [file, content] of index) {
    const abs = path.join(ROOT, file);
    if (fs.existsSync(abs) && fs.readFileSync(abs, "utf8") === content) continue;
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, content);
    changed++;
    console.log(`wrote ${file}`);
  }
  removeEmptyDirs(INDEX);
  console.log(`${INDEX}: ${index.size} files, ${changed} changed`);
}

function removeEmptyDirs(dir) {
  const abs = path.join(ROOT, dir);
  for (const e of fs.readdirSync(abs, { withFileTypes: true })) {
    if (e.isDirectory()) removeEmptyDirs(`${dir}/${e.name}`);
  }
  if (dir !== INDEX && fs.readdirSync(abs).length === 0) fs.rmdirSync(abs);
}

// ---------- check ----------

function check() {
  const wiki = loadWiki();
  const problems = [];
  const report = (file, n, msg) => problems.push(`${file}${n ? `:${n}` : ""}: ${msg}`);

  // Index is current.
  const index = buildIndex(wiki);
  for (const [file, content] of index) {
    if (!exists(file)) report(file, 0, "index file missing; run `node scripts/wiki.mjs`");
    else if (read(file) !== content) report(file, 0, "index is stale; run `node scripts/wiki.mjs`");
  }
  for (const file of currentIndexFiles()) {
    if (!index.has(file)) report(file, 0, "index file has no source directory; run `node scripts/wiki.mjs`");
  }

  // Links and anchors, in every markdown file under docs/ and AGENTS.md.
  const anchorCache = new Map();
  const anchorsOf = (file) => {
    if (!anchorCache.has(file)) anchorCache.set(file, new Set(headings(read(file)).map((h) => h.anchor)));
    return anchorCache.get(file);
  };
  const mdFiles = wiki.files.filter(
    (f) => (f.startsWith("docs/") && !f.startsWith("docs/specs/") && f.endsWith(".md")) || f === "AGENTS.md",
  );
  for (const file of mdFiles) {
    for (const { n, target } of links(read(file))) {
      if (/^[a-z][a-z0-9+.-]*:/i.test(target)) continue;
      const { file: to, anchor } = resolveLink(file, target);
      if (!exists(to)) report(file, n, `dead link ${target}`);
      else if (anchor && to.endsWith(".md") && !anchorsOf(to).has(anchor)) report(file, n, `dead anchor ${target}`);
    }
  }

  // Page layout.
  for (const page of wiki.pages) {
    const hs = headings(page.text);
    const h1s = hs.filter((h) => h.level === 1);
    if (hs[0]?.level !== 1) report(page.file, hs[0]?.n ?? 0, "the first heading must be the H1");
    if (h1s.length !== 1) report(page.file, h1s[1]?.n ?? 0, `expected one H1, found ${h1s.length}`);
    if (!page.topic) continue; // root files have their own layout
    // Descriptive sections may come before Rules; Rules and Code close the page, in that order.
    const h2s = hs.filter((h) => h.level === 2).map((h) => h.title);
    if (h2s.slice(-2).join("|") !== "Rules|Code" || h2s.filter((t) => t === "Rules" || t === "Code").length !== 2) {
      report(page.file, 0, `the last sections must be "## Rules" then "## Code", found ${h2s.map((t) => `"${t}"`).join(", ") || "none"}`);
    }
    if (!page.hasFrontmatter || !page.covers.length) report(page.file, 1, "page has no `covers`");
  }

  // Covers.
  for (const page of wiki.pages) {
    for (const m of page.matchers) {
      if (!wiki.files.some((f) => m.re.test(f))) report(page.file, 0, `covers "${m.glob}" matches no file`);
    }
  }
  for (const f of sourceFiles(wiki.files)) {
    if (!wiki.pages.some((p) => p.files.includes(f))) report(f, 0, "no wiki page covers this file");
  }

  // Glossaries.
  const termsByName = new Map();
  const linked = new Set();
  for (const g of wiki.glossaries) {
    for (const t of g.terms) {
      const len = [...t.line].length;
      if (len > MAX_GLOSSARY_LINE) report(g.file, t.n, `glossary line is ${len} characters (max ${MAX_GLOSSARY_LINE})`);
      if (!t.targets.length) report(g.file, t.n, `term "${t.name}" links to no page`);
      for (const l of t.targets) linked.add(l.file);
      // A line that only points to another glossary is a cross-reference, not a definition.
      if (t.targets.length && t.targets.every((l) => path.posix.basename(l.file) === "glossary.md")) continue;
      const key = t.name.toLowerCase();
      if (!termsByName.has(key)) termsByName.set(key, []);
      termsByName.get(key).push({ g, t });
    }
  }
  for (const defs of termsByName.values()) {
    const topics = new Set(defs.map((d) => d.g.file));
    if (topics.size > 1) {
      const where = defs.map((d) => `${d.g.file}:${d.t.n}`).join(", ");
      for (const d of defs) report(d.g.file, d.t.n, `term "${d.t.name}" is defined in more than one glossary (${where})`);
    }
  }

  // Orphans.
  for (const page of wiki.pages) {
    if (page.topic && !linked.has(page.file)) report(page.file, 0, "orphan page: no glossary term links to it");
  }

  if (problems.length) {
    console.error(problems.join("\n"));
    console.error(`\nwiki:check: ${problems.length} problem${problems.length === 1 ? "" : "s"}`);
    process.exit(1);
  }
  console.log(`wiki:check: ok (${wiki.pages.length} pages, ${index.size} index files)`);
}

// ---------- affected ----------

export function changedFiles() {
  const out = new Set();
  try {
    for (const f of git("diff", "--name-only", "HEAD", "-z").split("\0")) if (f) out.add(f);
  } catch {
    // No HEAD yet: everything staged counts.
    for (const f of git("diff", "--name-only", "--cached", "-z").split("\0")) if (f) out.add(f);
  }
  for (const f of git("ls-files", "--others", "--exclude-standard", "-z").split("\0")) if (f) out.add(f);
  return [...out].sort();
}

export function affectedPages(files) {
  const wiki = loadWiki();
  const result = [];
  for (const page of wiki.pages) {
    const hits = files.filter((f) => page.matchers.some((m) => m.re.test(f)));
    if (hits.length) result.push({ page: page.file, title: page.title, files: hits });
  }
  return result;
}

function affected(args) {
  const json = args.includes("--json");
  let files = args.filter((a) => a !== "--json");
  if (files.length === 1 && files[0] === "-") files = fs.readFileSync(0, "utf8").split(/\s+/).filter(Boolean);
  else if (!files.length) files = changedFiles();
  files = files.map((f) => posix(path.relative(ROOT, path.resolve(f))));
  const result = affectedPages(files);
  if (json) console.log(JSON.stringify(result, null, 2));
  else for (const r of result) console.log(`${r.page}\t${r.files.join(" ")}`);
}

// ---------- main ----------

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [cmd, ...args] = process.argv.slice(2);
  if (!readWikiConfig(ROOT)) {
    console.error("no `wiki` key in harness.json");
    process.exit(1);
  }
  if (!cmd || cmd === "build") writeIndex();
  else if (cmd === "check") check();
  else if (cmd === "affected") affected(args);
  else {
    console.error(`unknown command ${cmd}; use build, check or affected`);
    process.exit(2);
  }
}
